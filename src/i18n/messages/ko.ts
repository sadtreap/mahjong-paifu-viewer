/** Notes after a label: "" or ", a, b". */
function more(items: readonly string[]): string {
  return items.length === 0 ? "" : `, ${items.join(", ")}`;
}

/** 천봉 단위 (PlayerInfo.danIndex): 신인, 9-1급, 초단-10단, 천봉위. */
function dan(index: number): string {
  if (index <= 0) {
    return "신인";
  }
  if (index < 10) {
    return `${10 - index}급`;
  }
  if (index === 10) {
    return "초단";
  }
  return index < 20 ? `${index - 9}단` : "천봉위";
}

